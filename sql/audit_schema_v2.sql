/*
audit_schema_v2.sql
Drops and recreates audit.audit_log. Deletes all existing audit rows.
For development use while the table is empty.

JSON rules (enforced via CHECK constraints + application layer):
- insert:        old_values NULL; new_values = row snapshot (JSON object)
- update:        same keys in old_values and new_values; changed fields only
- soft delete:   action = 'delete'; old_values and new_values show soft-delete flag changes
- restore:       old_values and new_values show restored soft-delete flags
- hard delete:   old_values = row snapshot; new_values NULL
- login_failed:  email is allowed; password is never allowed
- Never store:   password, password_hash, token_hash, refresh_token_hash,
                 invite_token_hash, mailbox OAuth tokens, or any other
                 secret, token, or API key

Column rules:
- account_id: the acting account (or target portal account), taken from context
- request_id: a ULID generated by the backend for each request; do not
              store inbound X-Request-ID or trace headers here

Already applied on deevo_app_dev2. Run in SSMS as deevo_ddl.
Requires SQL Server 2022+ / compatibility level 160+ (2-arg ISJSON).
*/

USE [deevo_app_dev2];
GO

SET ANSI_NULLS ON;
GO
SET QUOTED_IDENTIFIER ON;
GO

IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = 'audit')
    EXEC('CREATE SCHEMA [audit] AUTHORIZATION [dbo]');
GO

DROP TABLE IF EXISTS [audit].[audit_log];
GO

CREATE TABLE [audit].[audit_log] (
    [id]          varchar(26)    NOT NULL,
    [tenant_id]   varchar(26)    NULL,
    [account_id]  varchar(26)    NULL,
    [session_id]  varchar(26)    NULL,
    [request_id]  varchar(26)    NULL,
    [user_id]     varchar(26)    NULL,
    [user_type]   varchar(20)    NULL,
    [schema_name] varchar(50)    NULL,
    [table_name]  varchar(100)   NULL,
    [record_id]   varchar(26)    NULL,
    [action]      varchar(20)    NOT NULL,
    [old_values]  nvarchar(max)  NULL,
    [new_values]  nvarchar(max)  NULL,
    [ip_address]  varchar(45)    NULL,
    [user_agent]  nvarchar(500)  NULL,
    [reason]      nvarchar(500)  NULL,
    [created_at]  datetime2(3)   NOT NULL
        CONSTRAINT [DF_audit_log_created_at] DEFAULT (sysutcdatetime()),

    CONSTRAINT [PK_audit_log] PRIMARY KEY CLUSTERED ([id] ASC),

    CONSTRAINT [CK_audit_log_action] CHECK (
        [action] IN (
            'insert', 'update', 'delete', 'restore',
            'login', 'login_failed', 'logout', 'access_denied',
            'export', 'import'
        )
    ),

    CONSTRAINT [CK_audit_log_user_type] CHECK (
        [user_type] IS NULL
        OR [user_type] IN ('system', 'tenant', 'tenant_account')
    ),

    /* Data changes must identify the record they changed. */
    CONSTRAINT [CK_audit_log_data_change_target] CHECK (
        [action] NOT IN ('insert', 'update', 'delete', 'restore')
        OR (
            [schema_name] IS NOT NULL
            AND [table_name] IS NOT NULL
            AND [record_id] IS NOT NULL
        )
    ),

    /* Data changes must supply appropriate old/new value snapshots. */
    CONSTRAINT [CK_audit_log_data_change_values] CHECK (
        ([action] = 'insert' AND [old_values] IS NULL AND [new_values] IS NOT NULL)
        OR ([action] IN ('update', 'restore') AND [old_values] IS NOT NULL AND [new_values] IS NOT NULL)
        OR ([action] = 'delete' AND [old_values] IS NOT NULL)
        OR ([action] NOT IN ('insert', 'update', 'delete', 'restore'))
    ),

    /* JSON payloads must be valid JSON objects ({...}). */
    CONSTRAINT [CK_audit_log_old_values_json] CHECK (
        [old_values] IS NULL OR ISJSON([old_values], OBJECT) = 1
    ),

    CONSTRAINT [CK_audit_log_new_values_json] CHECK (
        [new_values] IS NULL OR ISJSON([new_values], OBJECT) = 1
    )
);
GO

CREATE NONCLUSTERED INDEX [IX_audit_log_tenant_created]
    ON [audit].[audit_log] ([tenant_id] ASC, [created_at] DESC);

CREATE NONCLUSTERED INDEX [IX_audit_log_record_created]
    ON [audit].[audit_log] ([tenant_id] ASC, [schema_name] ASC, [table_name] ASC, [record_id] ASC, [created_at] DESC);

CREATE NONCLUSTERED INDEX [IX_audit_log_user_created]
    ON [audit].[audit_log] ([user_id] ASC, [created_at] DESC);

CREATE NONCLUSTERED INDEX [IX_audit_log_account_created]
    ON [audit].[audit_log] ([account_id] ASC, [created_at] DESC)
    WHERE [account_id] IS NOT NULL;

CREATE NONCLUSTERED INDEX [IX_audit_log_request]
    ON [audit].[audit_log] ([request_id] ASC, [created_at] DESC)
    WHERE [request_id] IS NOT NULL;
GO

/* Make the table append-only for the application role.
   If deevo_ddl lacks permission to run GRANT/DENY, run this block as dbo. */
IF DATABASE_PRINCIPAL_ID('deevo_app') IS NOT NULL
BEGIN
    GRANT SELECT, INSERT ON OBJECT::[audit].[audit_log] TO [deevo_app];
    DENY UPDATE, DELETE ON OBJECT::[audit].[audit_log] TO [deevo_app];
END;
GO
