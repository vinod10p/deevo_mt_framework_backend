/*
  The following rules intentionally remain in the application/service layer:

  1. txn.screen_field.section_id must belong to the same screen_id as
     txn.screen_field.screen_id.

  2. txn.lookup.return_field_key should correspond to an active,
     non-deleted txn.lookup_column.field_key for the same lookup.

  3. rpt.report_action.trigger_column_key should correspond to a valid
     source rpt.report_column key.

  4. For report actions:
       rpt.report_action_param.target_key should correspond to a valid
       rpt.report_criteria key on the target report.

  5. For source_type = 'column':
       source_key should correspond to a valid source report result column.

  6. For source_type = 'criteria':
       source_key should correspond to a valid source report criterion.

  7. For screen actions:
       target_key is interpreted by the target screen/API navigation contract
       (for example lead_id -> id).

  8. Tenant consistency:
       permission/config rows must be validated against the current tenant
       context by the service layer.

  9. permission_mode resolution:
       OPEN:
         - no permission row -> access follows report/screen defaults/capabilities
         - explicit permission row -> explicit permission applies

       RESTRICTED:
         - no permission row -> deny
         - explicit permission row -> explicit permission applies

  10. Screen effective operation:
       effective operation = screen allow_* capability
                             AND resolved user permission.

  11. All writes must:
       - update updated_at
       - use row_version for optimistic concurrency
       - write audit.audit_log in the same application transaction
       - soft-delete rather than hard-delete
*/

