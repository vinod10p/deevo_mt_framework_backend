        CHECK ([max_length] IS NULL OR [max_length] > 0),

    CONSTRAINT [CK_screen_field_min_max]
        CHECK ([min_value] IS NULL OR [max_value] IS NULL OR [min_value] <= [max_value]),

    CONSTRAINT [CK_screen_field_format_type]
        CHECK ([format_type] IS NULL OR
               [format_type] IN ('decimal','currency','percent','weight')),

    CONSTRAINT [CK_screen_field_lookup_control]
        CHECK (
            ([control_type] = 'dropdown' AND [lookup_id] IS NOT NULL)
            OR
            ([control_type] <> 'dropdown' AND [lookup_id] IS NULL)
        )
);
