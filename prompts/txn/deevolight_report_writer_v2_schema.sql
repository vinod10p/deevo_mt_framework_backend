        CHECK (
            (
                [action_type] = 'report'
                AND [target_report_id] IS NOT NULL
                AND [target_screen_id] IS NULL
                AND [screen_mode] IS NULL
            )
            OR
            (
                [action_type] = 'screen'
                AND [target_report_id] IS NULL
                AND [target_screen_id] IS NOT NULL
                AND [screen_mode] IN ('add','view')
            )
        ),

    CONSTRAINT [CK_report_action_trigger_column]
        CHECK (
            ([display_location] = 'column' AND [trigger_column_key] IS NOT NULL)
            OR
            ([display_location] IN ('toolbar','row') AND [trigger_column_key] IS NULL)
